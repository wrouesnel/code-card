func TestSemiRandomTableMatchesGo(t *testing.T) {
	vm := newVM(t)
	rng := rand.New(rand.NewPCG(1, 2)) //nolint:gosec // deterministic test inputs
	randomString := func(alphabet string, length int) string {
		var sb strings.Builder
		for range length {
			sb.WriteByte(alphabet[rng.IntN(len(alphabet))])
		}
		return sb.String()
	}

	for range 200 {
		salt := randomString("abcdefghijklmnopqrstuvwxyz0123456789!@#", 16+rng.IntN(20))
		keyword := randomString("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ", 1+rng.IntN(12))
		code := randomString("0123456789", rng.IntN(len(keyword)+1))

		table, err := codecard.SemiRandomTable(salt, code, keyword)
		if err != nil {
			// Too many repeats: check the JS implementation also rejects it.
			if _, jsErr := vm.RunString(fmt.Sprintf("CodeCard.semiRandomTable(%q, %q, %q)", salt, code, keyword)); jsErr == nil {
				t.Errorf("JS accepted (%q, %q, %q) which Go rejected: %v", salt, code, keyword, err)
			}
			continue
		}
		want := strings.Join(table.Rows(), ",")
		if got := call(t, vm, semiRandomTableJS, salt, code, keyword); got != want {
			t.Errorf("(%q, %q, %q): table mismatch:\n got: %s\nwant: %s", salt, code, keyword, got, want)
		}
	}
}

func TestSemiRandomTableErrors(t *testing.T) {
	vm := newVM(t)
	const salt = "1337code8Ackz0rs"
	cases := []struct{ salt, code, keyword, want string }{
		{"short", "1234", "word", "at least 16 bytes"},
		{salt, "12345", "word", "at least as long as the code"},
		{salt, "1234", "aaaa", "Too many repeated characters"},
		{salt, "", "", "only contain the letters"},
		{salt, "1234", "w0rd", "only contain the letters"},
		{salt, "12a4", "word", "only contain the digits"},
	}
	for _, tc := range cases {
		_, err := vm.RunString(fmt.Sprintf("CodeCard.semiRandomTable(%q, %q, %q)", tc.salt, tc.code, tc.keyword))
		if err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("(%q, %q, %q): got error %v, want %q", tc.salt, tc.code, tc.keyword, err, tc.want)
		}
	}
}

func TestRandomTable(t *testing.T) {
	vm := newVM(t)
	// Use a deterministic source since the embedded engine has no crypto.getRandomValues.
	rows := call(t, vm, `() => {
		const r = new CodeCard.PyRandom([1, 2, 3]);
		return CodeCard.tableRows(CodeCard.randomTable((n) => r.randBelow(n))).join(",");
	}`)
	counts := map[byte]int{}
	for idx, row := range strings.Split(rows, ",") {
		if len(row) != 3 || row[0] != byte('A'+idx) || row[2] < '0' || row[2] > '9' {
			t.Fatalf("invalid row %q", row)
		}
		counts[row[2]]++
	}
	for digit := byte('0'); digit <= '9'; digit++ {
		if counts[digit] < 2 {
			t.Errorf("digit %c used %d times, want at least 2", digit, counts[digit])
		}
	}
}

func TestRandomSalt(t *testing.T) {
	vm := newVM(t)
	salt := call(t, vm, `() => {
		const r = new CodeCard.PyRandom([4, 5, 6]);
		return CodeCard.randomSalt((n) => r.randBelow(n));
	}`)
	if len(salt) != 24 || strings.Trim(salt, "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789") != "" {
		t.Fatalf("invalid salt %q", salt)
	}
	// Random salts must be accepted for encoded cards.
	if _, err := codecard.SemiRandomTable(salt, "1234", "word"); err != nil {
		t.Errorf("salt %q rejected: %v", salt, err)
	}
}
